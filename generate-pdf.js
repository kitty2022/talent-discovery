function font(size, bold = false) {
  doc.font(bold ? 'YaHei-Bold' : 'YaHei', size);
}

function title(text, size = 24) {
  doc.y += 10;
  font(size, true);
  doc.fillColor('#1e293b').text(text, { align: 'center' });
  doc.moveDown(0.5);
}

function h1(text) {
  doc.y += 15;
  font(18, true);
  doc.fillColor('#4f46e5').text(text);
  doc.moveDown(0.5);
  font(10, false);
  doc.fillColor('#cbd5e1')
    .moveTo(doc.x, doc.y)
    .lineTo(doc.page.width - doc.page.margins.right, doc.y)
    .stroke();
  doc.moveDown(0.8);
}

function h2(text) {
  doc.y += 10;
  font(14, true);
  doc.fillColor('#6366f1').text(text);
  doc.moveDown(0.5);
}

function h3(text) {
  font(12, true);
  doc.fillColor('#475569').text(text);
  doc.moveDown(0.3);
}

function p(text) {
  font(10, false);
  doc.fillColor('#334155').text(text, { lineGap: 4 });
  doc.moveDown(0.3);
}

function bullet(text) {
  font(10, false);
  doc.fillColor('#334155').text(`  • ${text}`, { indent: 15, lineGap: 3 });
}

function numbered(num, text) {
  font(10, false);
  doc.fillColor('#334155').text(`  ${num}. ${text}`, { indent: 15, lineGap: 3 });
}

function questionTable(questions, headers = ['序号', '问题', '维度', '选项/方向']) {
  doc.y += 5;
  const colWidths = [30, 260, 80, 90];
  const totalWidth = colWidths.reduce((a, b) => a + b, 0);
  const startX = doc.x + 20;

  // 表头
  font(9, true);
  doc.fillColor('#ffffff');
  let x = startX;
  doc.rect(startX - 3, doc.y, totalWidth + 6, 22).fill('#6366f1');
  doc.fillColor('#ffffff');
  x = startX;
  headers.forEach((h, i) => {
    doc.text(h, x + 3, doc.y + 4, { width: colWidths[i], align: 'center' });
    x += colWidths[i];
  });
  doc.moveDown(2.5);

  // 数据行
  questions.forEach((row, idx) => {
    const bg = idx % 2 === 0 ? '#f8fafc' : '#ffffff';
    font(8.5, false);
    doc.fillColor('#334155');
    x = startX;
    doc.rect(startX - 3, doc.y - 3, totalWidth + 6, 20).fill(bg);
    doc.fillColor('#334155');
    row.forEach((cell, i) => {
      doc.text(String(cell), x + 3, doc.y, { width: colWidths[i], align: i === 0 ? 'center' : 'left' });
      x += colWidths[i];
    });
    doc.moveDown(1.3);
  });
  doc.moveDown(0.5);
}

function checkPageBreak(needed = 150) {
  if (doc.y + needed > doc.page.height - doc.page.margins.bottom) {
    doc.addPage();
  }
}

