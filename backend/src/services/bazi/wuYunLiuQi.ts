const EXCESS_RISK: Record<string, string> = {
  '太过': '「太过」意味着该元素能量过强，容易过度消耗对应的脏腑，需注意节制和疏导。',
  '不及': '「不及」意味着该元素能量偏弱，对应的脏腑先天不足，需注意补养和维护。',
};

function analyzeRisk(yun: string, excess: string, siTian: string): string {
  const baseRisk = RISK_MAP[yun]?.[siTian] || '';
  const excessNote = EXCESS_RISK[excess] || '';
  return baseRisk + '\n\n' + excessNote;
}

export function calculateWuYunLiuQi(yearStem: string, yearBranch: string): WuYunLiuQiResult {
  // 五运
  const yunInfo = TIAN_GAN_YUN[yearStem] || { yun: '土', excess: '平和' };
  const yunTiZhi = WU_YUN_TI_ZHI[yunInfo.yun] || '';

  // 六气
  const qiInfo = DI_ZHI_QI[yearBranch] || { siTian: '厥阴风木', zaiQuan: '少阳相火', description: '' };
  const qiTiZhi = SI_TIAN_TI_ZHI[qiInfo.siTian] || '';

  // 综合结论
  const conclusion = analyzeRisk(yunInfo.yun, yunInfo.excess, qiInfo.siTian);
  const herbs = HERB_MAP[yunInfo.yun]?.[qiInfo.siTian] || '建议咨询专业中医师进行辨证论治。';

  const constitution = `出生之年为${yearStem}${yearBranch}年，${yunInfo.yun}运${yunInfo.excess}，${qiInfo.siTian}司天。\n\n` +
    `【五运】${yunInfo.yun}运${yunInfo.excess}：${yunTiZhi}\n\n` +
    `【六气】${qiInfo.siTian}司天，${qiInfo.zaiQuan}在泉：${qiTiZhi}\n\n` +
    `【易发问题】${conclusion}\n\n` +
    `【参考用药】${herbs}\n\n` +
    `【养生建议】根据先天运气格局，${yunInfo.yun}运${yunInfo.excess}体质在对应的${yunInfo.yun}系脏腑上需要多加关注，` +
    `同时${qiInfo.siTian}司天的气候影响也会对特定系统造成压力。日常生活中注意针对性调理，` +
    `可以大大降低这些先天倾向带来的健康风险。\n\n` +
    `⚠️ 以上用药建议仅供学习参考，实际用药请咨询专业中医师。`;

  return {
    wuYun: {
      yearStem,
      yun: yunInfo.yun,
      excess: yunInfo.excess,
      description: `${yearStem}年→${yunInfo.yun}运${yunInfo.excess}`,
      tiZhi: yunTiZhi,
    },
    liuQi: {
      yearBranch,
      siTian: qiInfo.siTian,
      zaiQuan: qiInfo.zaiQuan,
      description: qiInfo.description,
      tiZhi: qiTiZhi,
    },
    constitution,
    conclusion,
    herbs,
  };
}
